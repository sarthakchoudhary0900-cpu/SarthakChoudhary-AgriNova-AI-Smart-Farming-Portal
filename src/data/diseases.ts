export function getDiseasesForCrop(cropName: string): DiseaseInfo[] {
  const diseases: DiseaseInfo[] = [];
  for (const disease of Object.values(diseaseDatabase)) {
    if (disease.crops.some(c => cropName.toLowerCase().includes(c.toLowerCase()) || c.toLowerCase().includes(cropName.toLowerCase()))) {
      diseases.push(disease);
    }
  }
  return diseases;
}

export function getAllDiseaseNames(): string[] {
  return Object.values(diseaseDatabase).map(d => d.name);
}
